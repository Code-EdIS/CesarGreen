/* =========================================================
   LANGUAGE STATE
   ========================================================= */

let currentLanguage = "it";

try {
    currentLanguage =
        localStorage.getItem("cesar-language") === "en"
            ? "en"
            : "it";
} catch (error) {
    currentLanguage = "it";
}


/* =========================================================
   TRANSLATION HELPER
   ========================================================= */

function t(key) {
    return translations[currentLanguage][key] || key;
}


/* =========================================================
   APPLY TRANSLATIONS
   ========================================================= */

function applyTranslations() {
    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        element.textContent = t(element.dataset.i18n);
    });

    document.querySelectorAll("[data-i18n-html]").forEach(element => {
        element.innerHTML = t(element.dataset.i18nHtml);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        element.placeholder = t(element.dataset.i18nPlaceholder);
    });

    const button = document.getElementById("lang");

    if (button) {
        const nextLanguage =
            currentLanguage === "it" ? "EN" : "IT";

        button.innerHTML = `${nextLanguage} <span>↗</span>`;

        button.setAttribute(
            "aria-label",
            currentLanguage === "it"
                ? "Switch to English"
                : "Passa all'italiano"
        );
    }

    const pageTitles = {
        "page-home": "CESAR GREEN — Security, by Nature.",
        "page-about": "About — CESAR GREEN",
        "page-products": "Products — CESAR GREEN",
        "page-contacts": "Contacts — CESAR GREEN"
    };

    for (const [className, title] of Object.entries(pageTitles)) {
        if (document.body.classList.contains(className)) {
            document.title = title;
            break;
        }
    }

    document.dispatchEvent(
        new CustomEvent("languagechange", {
            detail: {
                language: currentLanguage
            }
        })
    );
}


/* =========================================================
   SWITCH LANGUAGE
   ========================================================= */

function switchLanguage() {
    currentLanguage =
        currentLanguage === "it" ? "en" : "it";

    try {
        localStorage.setItem(
            "cesar-language",
            currentLanguage
        );
    } catch (error) {
        // Language still changes for the current page.
    }

    applyTranslations();
}


/* =========================================================
   INITIALIZATION
   ========================================================= */

document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();

    document
        .getElementById("lang")
        ?.addEventListener("click", switchLanguage);
});
